"""The four logical agents + Copilot.

Each agent: gathers context through its bounded tools (recorded), calls the AI gateway with a
typed schema, validates that every cited evidence ID exists, and falls back to a
deterministic implementation when no model is available or output is rejected.
"""

from __future__ import annotations

import re
import uuid
from datetime import timedelta
from typing import Any

from sqlalchemy import select
from sqlalchemy.orm import Session

from aseo.agents import runtime
from aseo.agents.schemas import (
    AuditReport,
    ContentBrief,
    CopilotAnswer,
    IssueCluster,
    KeywordOpportunity,
    MeasurementReport,
    MetadataDraft,
    PlanItemOut,
    ProposedAction,
    StrategyPlan,
)
from aseo.ai.gateway import AIResult, Gateway, untrusted
from aseo.models import ActionPlan, AgentRun, ChangeSet, ExecutionRun, PlanItem, SearchMetric, Site
from aseo.services.validation import validate_value

SEV_ORDER = {"critical": 0, "high": 1, "medium": 2, "low": 3, "info": 4}


def _known_ids(*collections: Any) -> set[str]:
    ids: set[str] = set()

    def walk(x: Any) -> None:
        if isinstance(x, dict):
            for k, v in x.items():
                if k == "evidence_id" and isinstance(v, str):
                    ids.add(v)
                else:
                    walk(v)
        elif isinstance(x, list):
            for i in x:
                walk(i)

    for c in collections:
        walk(c)
    return ids


# ======================================================================= Audit agent


def audit_agent(db: Session, site: Site, *, workflow_run_id: uuid.UUID | None = None, gateway: Gateway | None = None) -> AgentRun:
    gw = gateway or Gateway()
    run = runtime.start_run(db, site=site, agent="audit", task="explain_findings", input={"site_id": str(site.id)},
                            workflow_run_id=workflow_run_id, gateway=gw)
    tools = runtime.Tools(db, site, run)
    findings = tools.list_findings(limit=40)
    sitemap = tools.inspect_sitemap()
    known = _known_ids(findings)

    def fallback() -> AuditReport:
        groups: dict[str, list[dict[str, Any]]] = {}
        for f in findings:
            groups.setdefault(f["category"], []).append(f)
        clusters = []
        for cat, fs in sorted(groups.items(), key=lambda kv: min(SEV_ORDER[f["severity"]] for f in kv[1])):
            top = min(SEV_ORDER[f["severity"]] for f in fs)
            clusters.append(IssueCluster(
                title=f"{cat.replace('_', ' ').title()}: {len(fs)} issue type{'s' if len(fs) > 1 else ''}",
                explanation="; ".join(f"{f['title']} ({f['affected']} affected, {f['kind']})" for f in fs[:6]),
                finding_ids=[f["id"] for f in fs], evidence_ids=[f["evidence_id"] for f in fs],
                priority="now" if top <= 1 else "next" if top == 2 else "later",
                deterministic=all(f["kind"] == "deterministic" for f in fs)))
        return AuditReport(
            summary=f"{len(findings)} open issue types across {sitemap['pages_crawled']} crawled pages. "
                    "Deterministic defects are listed before heuristic opportunities.",
            clusters=clusters,
            limitations=["Generated by deterministic rules without an AI model.", "Health score is an internal diagnostic, not a Google metric."],
        )

    result = gw.run(
        task="audit.explain", prompt_version="audit-v1",
        system="You are the Audit Agent. Group SEO findings into clusters a site owner can act on, explain each in plain language, "
               "and keep deterministic defects separate from heuristic opportunities.",
        prompt=f"Site: {site.domain}\nSitemap summary: {sitemap}\n\nFindings:\n{untrusted('data', findings)}",
        schema=AuditReport, fallback=fallback,
        validate=lambda r: runtime.check_citations([e for c in r.clusters for e in c.evidence_ids], known),
    )
    runtime.finish_run(db, run, result, evidence_ids=sorted({e for c in result.output.clusters for e in c.evidence_ids}))
    return run


# ======================================================================= Strategy agent

ACTION_IMPACT = {"meta_description": ("medium", "low"), "title": ("high", "low")}


def strategy_agent(db: Session, site: Site, *, workflow_run_id: uuid.UUID | None = None, gateway: Gateway | None = None,
                   created_by: uuid.UUID | None = None) -> tuple[AgentRun, ActionPlan]:
    gw = gateway or Gateway()
    run = runtime.start_run(db, site=site, agent="strategy", task="prioritize_plan", input={"goals": site.business_goals},
                            workflow_run_id=workflow_run_id, gateway=gw)
    tools = runtime.Tools(db, site, run)
    findings = tools.get_findings(limit=40)
    queries = tools.get_search_queries(limit=40)
    known = _known_ids(findings, queries)

    def fallback() -> StrategyPlan:
        ordered = sorted(findings, key=lambda f: (SEV_ORDER[f["severity"]], f["kind"] != "deterministic", -f["affected"]))
        items = []
        for i, f in enumerate(ordered[:15]):
            impact, effort = ACTION_IMPACT.get(f["fix_action"] or "", ("medium" if SEV_ORDER[f["severity"]] <= 2 else "low", "medium"))
            items.append(PlanItemOut(finding_id=f["id"], action_type=f["fix_action"] or "manual_review", title=f["title"],
                                     rationale=f"{f['severity'].title()} {f['kind']} issue affecting {f['affected']} URL(s).",
                                     priority=i + 1, impact=impact, effort=effort, evidence_ids=[f["evidence_id"]]))
        opps = []
        for q in queries:
            if q["impressions"] >= 100 and (q["ctr"] or 0) < 0.02 and q["position"] and q["position"] <= 15:
                opps.append(KeywordOpportunity(query=q["query"], page_url=q["page"], source="demo_fixture" if q["source"] != "gsc" else "gsc",
                                               reason=f"{q['impressions']} impressions at avg. position {q['position']:.1f} with CTR "
                                                      f"{(q['ctr'] or 0) * 100:.1f}% — the snippet may be under-performing.",
                                               evidence_ids=[q["evidence_id"]]))
        return StrategyPlan(title=f"Action plan for {site.name}", summary="Prioritised by severity, determinism and reach.",
                            items=items, keyword_opportunities=opps[:10],
                            caveats=["Ordering is rule-based (no AI model).", "Outcomes in search are not guaranteed."])

    result = gw.run(
        task="strategy.plan", prompt_version="strategy-v1",
        system="You are the Strategy Agent. Produce a prioritised action plan. Prefer fixes with deterministic evidence, broad reach and "
               "low effort. Keyword opportunities must come from the provided query data only — never invent search volumes.",
        prompt=f"Business goals: {site.business_goals or 'not provided'}\n\nFindings:\n{untrusted('data', findings)}\n\n"
               f"Search queries:\n{untrusted('data', queries)}",
        schema=StrategyPlan, fallback=fallback,
        validate=lambda p: runtime.check_citations([e for it in p.items for e in it.evidence_ids] +
                                                   [e for o in p.keyword_opportunities for e in o.evidence_ids], known),
    )
    plan_out: StrategyPlan = result.output
    plan = ActionPlan(tenant_id=site.tenant_id, site_id=site.id, title=plan_out.title, summary=plan_out.summary,
                      goals={"business_goals": site.business_goals, "caveats": plan_out.caveats,
                             "keyword_opportunities": [o.model_dump() for o in plan_out.keyword_opportunities]},
                      agent_run_id=run.id, created_by=created_by)
    db.add(plan)
    db.flush()
    valid_findings = {f["id"] for f in findings}
    for it in plan_out.items:
        db.add(PlanItem(tenant_id=site.tenant_id, plan_id=plan.id,
                        finding_id=uuid.UUID(it.finding_id) if it.finding_id in valid_findings else None,
                        action_type=it.action_type, title=it.title, rationale=it.rationale, priority=it.priority, impact=it.impact,
                        effort=it.effort, evidence_ids=it.evidence_ids))
    runtime.finish_run(db, run, result, evidence_ids=sorted({e for it in plan_out.items for e in it.evidence_ids}),
                       extra={"plan_id": str(plan.id)})
    return run, plan


def _trim(text: str, limit: int) -> str:
    text = re.sub(r"\s+", " ", text).strip()
    if len(text) <= limit:
        return text
    cut = text[:limit].rsplit(" ", 1)[0].rstrip(",;:-")
    return cut + "."


def propose_metadata(db: Session, site: Site, *, url: str, action_type: str, gateway: Gateway | None = None,
                     workflow_run_id: uuid.UUID | None = None) -> tuple[AgentRun, MetadataDraft]:
    gw = gateway or Gateway()
    run = runtime.start_run(db, site=site, agent="strategy", task=f"propose_{action_type}", input={"url": url},
                            workflow_run_id=workflow_run_id, gateway=gw)
    tools = runtime.Tools(db, site, run)
    snap = tools.get_page_snapshot(url, _tool="propose_metadata") or {"url": url}
    known = _known_ids(snap)
    limit = 155 if action_type == "meta_description" else 60

    def fallback() -> MetadataDraft:
        title = (snap.get("title") or "").split(" – ")[0].split(" | ")[0].strip()
        h1 = snap.get("h1") or title
        excerpt = snap.get("first_paragraph") or (snap.get("text_excerpt") or "").replace(h1 or "", "", 1).strip()
        if action_type == "title":
            value = _trim(f"{h1} | {site.name}" if h1 else site.name, limit).rstrip(".")
        else:
            sentences = re.split(r"(?<=[.!?])\s+", excerpt)
            body = ""
            for s in sentences:
                if len(body) + len(s) > limit:
                    break
                body = f"{body} {s}".strip()
            value = body or f"{h1}. Learn more from {site.name}."
            if len(value) < 70:
                value = _trim(f"{h1}: {value}" if h1 and h1 not in value else f"{value} Learn more at {site.name}.", limit)
            value = _trim(value, limit)
        return MetadataDraft(value=value, rationale="Template draft built from the page's H1 and opening text (no AI model used). "
                                                   "Review the wording before approving.",
                             evidence_ids=[snap["evidence_id"]] if snap.get("evidence_id") else [])

    def validate(d: MetadataDraft) -> list[str]:
        problems = runtime.check_citations(d.evidence_ids, known)
        v = validate_value(action_type, d.value, before=snap.get(action_type))
        return problems + v["errors"]

    noun = "meta description (about 120-155 characters)" if action_type == "meta_description" else "SEO title (about 40-60 characters)"
    result = gw.run(
        task=f"strategy.propose_{action_type}", prompt_version="metadata-v1",
        system=f"You are the Strategy Agent drafting a {noun}. Describe what the page actually offers using only facts from the page "
               "snapshot. No clickbait, no claims that are not on the page, no quotes, no HTML.",
        prompt=f"Site name: {site.name}\nPage snapshot:\n{untrusted('page_content', snap)}",
        schema=MetadataDraft, fallback=fallback, validate=validate,
    )
    runtime.finish_run(db, run, result, evidence_ids=result.output.evidence_ids)
    return run, result.output


def draft_content(db: Session, site: Site, *, target_query: str, notes: str | None = None, gateway: Gateway | None = None) -> tuple[AgentRun, ContentBrief]:
    gw = gateway or Gateway()
    run = runtime.start_run(db, site=site, agent="strategy", task="draft_content", input={"target_query": target_query}, gateway=gw)
    tools = runtime.Tools(db, site, run)
    queries = [q for q in tools.get_search_queries(limit=100) if any(w in q["query"] for w in target_query.lower().split())][:15]

    def fallback() -> ContentBrief:
        return ContentBrief(
            title=target_query.strip().capitalize(), target_query=target_query, search_intent="To be confirmed by an editor",
            outline=["Introduction: who this is for", f"What '{target_query}' means", "Step-by-step guidance", "Common mistakes", "FAQ", "Next steps"],
            key_points=[f"Related query seen in Search Console: {q['query']}" for q in queries[:5]] or ["Add first-hand expertise and examples"],
            internal_link_suggestions=[q["page"] for q in queries[:3] if q.get("page")],
            sources_needed=["Primary sources or first-hand data to support claims"],
            draft_markdown=f"# {target_query.strip().capitalize()}\n\n> Draft outline generated without an AI model. An editor must write and "
                           f"approve the content before publication.\n\n## Introduction\n\n_TODO_\n",
            caveats=["Template brief — no AI model configured.", "Drafts are never published automatically."],
        )

    result = gw.run(
        task="strategy.draft_content", prompt_version="content-v1", effort="medium",
        system="You are the Strategy Agent writing a content brief and first draft for a human editor. Mark any factual claim that needs a "
               "source with [source needed]. Do not invent statistics.",
        prompt=f"Site: {site.name} ({site.domain})\nTarget query: {target_query}\nEditor notes: {notes or '-'}\n"
               f"Related queries:\n{untrusted('data', queries)}",
        schema=ContentBrief, fallback=fallback,
    )
    runtime.finish_run(db, run, result, evidence_ids=[q["evidence_id"] for q in queries])
    return run, result.output


# ======================================================================= Execution agent (deterministic)


def execution_agent_propose(db: Session, site: Site, *, url: str, action_type: str, finding_id: uuid.UUID | None, actor: Any,
                            gateway: Gateway | None = None) -> ChangeSet:
    """Execution Agent: turns a draft into an immutable proposed patch and routes it through
    validation + policy (request_approval). It has no ability to bypass policy."""
    from aseo.services import changes

    draft_run, draft = propose_metadata(db, site, url=url, action_type=action_type, gateway=gateway)
    exec_run = AgentRun(tenant_id=site.tenant_id, site_id=site.id, agent="execution", task="prepare_patch",
                        input={"url": url, "action_type": action_type, "draft_run": str(draft_run.id)}, status="running",
                        provider="deterministic", model="policy-engine", prompt_version="execution-v1")
    db.add(exec_run)
    db.flush()
    for tool in ("prepare_patch", "validate_patch", "request_approval"):
        db.add(runtime.ToolInvocation(tenant_id=site.tenant_id, agent_run_id=exec_run.id, tool=tool, args={"url": url}, status="ok"))
    cs = changes.propose(db, actor=actor, site=site, url=url, action_type=action_type, value=draft.value, finding_id=finding_id,
                         source="deterministic" if draft_run.provider == "deterministic" else "ai", rationale=draft.rationale,
                         evidence_ids=draft.evidence_ids, agent_run_id=draft_run.id)
    exec_run.status = "succeeded"
    exec_run.output = {"change_set_id": str(cs.id), "status": cs.status, "policy": cs.policy_decision}
    return cs


# ======================================================================= Measurement agent


def measurement_agent(db: Session, site: Site, change: ChangeSet, *, gateway: Gateway | None = None) -> AgentRun:
    gw = gateway or Gateway()
    run = runtime.start_run(db, site=site, agent="measurement", task="after_change", input={"change_set_id": str(change.id)},
                            gateway=gw, charge=False)
    tools = runtime.Tools(db, site, run)
    history = tools.get_execution_history(limit=5)
    exec_row = db.execute(select(ExecutionRun).where(ExecutionRun.change_set_id == change.id, ExecutionRun.kind == "apply")
                          .order_by(ExecutionRun.created_at.desc()).limit(1)).scalar_one_or_none()
    url = (change.resource_ref or {}).get("url")
    metrics = tools.get_gsc_metrics(page=url)
    known = _known_ids(history)
    changed_on = exec_row.finished_at.date() if exec_row and exec_row.finished_at else None

    def window(days_from: int, days_to: int) -> dict[str, float | int | None]:
        if not changed_on:
            return {"clicks": None, "impressions": None, "ctr": None}
        lo, hi = changed_on + timedelta(days=days_from), changed_on + timedelta(days=days_to)
        rows = [m for m in metrics if lo.isoformat() <= m["date"] < hi.isoformat()]
        clicks = sum(m["clicks"] for m in rows)
        imps = sum(m["impressions"] for m in rows)
        return {"clicks": clicks, "impressions": imps, "ctr": round(clicks / imps, 4) if imps else None, "days": len({m['date'] for m in rows})}

    def fallback() -> MeasurementReport:
        before, after = window(-28, 0), window(3, 31)
        verified = bool(exec_row and exec_row.status == "succeeded")
        warnings = []
        if before.get("clicks") and after.get("clicks") is not None and after.get("days", 0) >= 14 and after["clicks"] < before["clicks"] * 0.7:
            warnings.append("Clicks for this page fell more than 30% after the change. Investigate before attributing causality.")
        return MeasurementReport(
            technical_outcome="verified" if verified else "not_verified",
            summary=("The change was verified live on the page. " if verified else "The change has not been verified. ")
            + ("Not enough post-change Search Console data yet (needs at least 14 days)." if (after.get("days") or 0) < 14
               else "Search performance comparison is shown below."),
            before=before, after=after, regression_warnings=warnings,
            caveats=["Search Console data is delayed 2-3 days and sampled.", "Seasonality, algorithm updates and other site changes "
                     "can explain differences; this is not proof of causation."],
            evidence_ids=[h["evidence_id"] for h in history[:1]],
        )

    # Numeric before/after analysis is deterministic statistics, never model-generated.
    result = AIResult(fallback(), "deterministic", "measurement-rules", "measurement-v1", 0, 0, 0.0, 0,
                      note="Measurement uses deterministic statistics.")
    _ = known
    runtime.finish_run(db, run, result, evidence_ids=result.output.evidence_ids)
    return run


# ======================================================================= Copilot


def copilot(db: Session, site: Site, *, question: str, gateway: Gateway | None = None) -> tuple[AgentRun, CopilotAnswer]:
    gw = gateway or Gateway()
    run = runtime.start_run(db, site=site, agent="copilot", task="answer", input={"question": question[:2000]}, gateway=gw)
    tools = runtime.Tools(db, site, run)
    findings = tools.list_findings(limit=30)
    urls = re.findall(r"https?://\S+", question)
    paths = re.findall(r"(?:^|\s)(/[\w\-/]*)", question)
    snaps = [s for s in (tools.get_page_snapshot(u.rstrip(".,?")) for u in urls) if s]
    for p in paths[:2]:
        s = tools.get_page_snapshot(site.base_url.rstrip("/") + p)
        if s:
            snaps.append(s)
    queries = tools.get_search_queries(limit=20)
    history = tools.get_execution_history(limit=10)
    known = _known_ids(findings, snaps, queries, history)

    def fallback() -> CopilotAnswer:
        generic = {"page", "pages", "which", "what", "site", "website", "there", "have", "does", "should", "with", "about", "issue", "issues", "first"}
        words = {w.rstrip("s") for w in re.findall(r"[a-z]{4,}", question.lower())} - generic

        def overlap(f: dict[str, Any]) -> int:
            terms = {w.rstrip("s") for w in re.findall(r"[a-z]{4,}", (f["title"] + " " + f["rule"].replace("_", " ")).lower())}
            return len(words & terms)

        scored = sorted(((overlap(f), f) for f in findings), key=lambda x: (-x[0], SEV_ORDER[x[1]["severity"]]))
        relevant = [f for s, f in scored if s > 0] or [f for _, f in scored[:5]]
        lines = [f"- {f['title']} — {f['affected']} affected ({f['severity']}, {f['kind']})" for f in relevant[:8]]
        actions = []
        for f in relevant:
            if f["fix_action"] in ("meta_description", "title") and f["examples"]:
                actions.append(ProposedAction(action_type=f["fix_action"], url=f["examples"][0]["url"], value="",
                                              rationale=f"Fix '{f['title']}' on this page (draft will be generated).",
                                              evidence_ids=[f["evidence_id"]]))
        return CopilotAnswer(
            answer=("Here is what the latest crawl shows that relates to your question:\n" + "\n".join(lines)) if lines
            else "The latest crawl has no open findings related to that question.",
            citations=[f["evidence_id"] for f in relevant[:8]], proposed_actions=actions[:3],
            limitations=["No AI model configured: this answer is a keyword match over the site's findings.",
                         "Only data from this site's crawls, Search Console sync and change history is used."],
        )

    result = gw.run(
        task="copilot.answer", prompt_version="copilot-v1", effort="medium",
        system="You are the Lodestar Copilot answering questions about ONE website using only the evidence provided. Cite evidence IDs. "
               "If the evidence cannot answer the question, say so. Proposed actions must be meta_description or title changes for URLs "
               "present in the evidence; leave value empty if you are unsure (a draft will be generated and reviewed).",
        prompt=f"Question: {question}\n\nFindings:\n{untrusted('data', findings)}\n\nPage snapshots:\n{untrusted('page_content', snaps)}\n\n"
               f"Search queries:\n{untrusted('data', queries)}\n\nRecent changes:\n{untrusted('data', history)}",
        schema=CopilotAnswer, fallback=fallback,
        validate=lambda a: runtime.check_citations(a.citations + [e for pa in a.proposed_actions for e in pa.evidence_ids], known),
    )
    runtime.finish_run(db, run, result, evidence_ids=result.output.citations)
    return run, result.output


